#!/usr/bin/env python3
"""Bake SPIR-V shaders into a C++ header for the Vulkan backend.

Usage:
    tools/compile_shaders.py --glslc <ndk>/shader-tools/<host>/glslc [--out DIR]

glslc ships with the NDK (r12+), so CI never downloads a shader compiler. All
four GLSL stages are checked: the two Vulkan ones compiled to SPIR-V, the two
GLES ones only syntax-checked, because OpenGL ES takes GLSL source at runtime.
"""
import argparse
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADER_DIR = ROOT / "shaders"
DEFAULT_OUT = ROOT / "app" / "src" / "main" / "cpp" / "render"

VULKAN_STAGES = [("scene.vert", "vertex"), ("scene.frag", "fragment")]



def encode(blob: bytes, per_line: int = 16) -> str:
    """Formats SPIR-V as an unsigned char initialiser, one byte per element.

    Vulkan reinterprets the buffer as uint32 words; emitting bytes keeps the
    header type-correct (a uint32 literal in a char array is a narrowing error
    in C++11 and later) and byte-order neutral.
    """
    lines = []
    for i in range(0, len(blob), per_line):
        chunk = ", ".join(f"0x{byte:02x}" for byte in blob[i:i + per_line])
        lines.append("    " + chunk + ",")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--glslc", required=True, help="path to the NDK glslc binary")
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()

    glslc = shutil.which(args.glslc) or args.glslc
    if not pathlib.Path(glslc).exists():
        print(f"error: glslc not found at {glslc}", file=sys.stderr)
        return 1

    out_dir = pathlib.Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    parts = []
    for source, stage in VULKAN_STAGES:
        src = SHADER_DIR / source
        dst = out_dir / f"{source}.spv"
        subprocess.run([glslc, "--target-env=vulkan1.1", "-O", str(src), "-o", str(dst)], check=True)
        blob = dst.read_bytes()
        parts.append((f"kSpirv{'Vertex' if stage == 'vertex' else 'Fragment'}", stage, blob))
        print(f"compiled {source} -> {dst.name} ({len(blob)} bytes)")

    header = ["/* Generated by tools/compile_shaders.py — do not edit. */",
              "#ifndef DIAMOND_SHADER_BIN_DATA_H", "#define DIAMOND_SHADER_BIN_DATA_H",
              "#include <cstddef>", "", "#define DIAMOND_HAVE_SPV 1"]
    for name, _stage, blob in parts:
        header.append(f"static const unsigned char {name}[] = {{")
        header.append(encode(blob))
        header.append("};")
        header.append(f"static const size_t {name}Size = sizeof({name});")
    header += [
        "inline const unsigned char *dshader_spirv_vertex(void) { return kSpirvVertex; }",
        "inline size_t dshader_spirv_vertex_size(void) { return kSpirvVertexSize; }",
        "inline const unsigned char *dshader_spirv_fragment(void) { return kSpirvFragment; }",
        "inline size_t dshader_spirv_fragment_size(void) { return kSpirvFragmentSize; }",
        "", "#endif", ""]
    (out_dir / "shader_bin_data.h").write_text("\n".join(header))
    print(f"wrote {out_dir / 'shader_bin_data.h'}")

    # The GLES shaders are C++ raw strings compiled by the driver at runtime;
    # tools/check_gles_shaders.py extracts and checks them without a GPU.
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
